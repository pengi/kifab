"""The optional KiCad plugin: toolbar buttons in KiCad that open kifab.

kifab manages KiCad, never the other way round (plan.md, increment 10). The
plugin is a thin launcher: its buttons start ``kifab-gui`` for the project open
in KiCad (optionally on the Parts tab). It holds no logic; the project works the
same without it.

It is a KiCad 9/10 IPC-API plugin (``plugin.json`` per KiCad's
``api.v1.schema.json``, Python runtime). KiCad creates a virtual environment for
it with ``requirements.txt`` (kicad-python), runs an action's script with
``KICAD_API_SOCKET``/``KICAD_API_TOKEN`` set, and the script asks KiCad which
project is open. The IPC API server must be enabled in KiCad's preferences
(Preferences > Plugins).
"""

from __future__ import annotations

import json
import shutil
import struct
import sys
import zlib
from dataclasses import dataclass
from pathlib import Path

from kifab import __version__

PLUGIN_ID = "com.github.pengi.kifab"
PLUGIN_DIR_NAME = "kifab"
KICAD_SERIES = "10.0"
CONFIG_NAME = "kifab-plugin.json"

#: (action id, button name, description, script, extra kifab-gui args)
ACTIONS = (
    (
        "open",
        "kifab",
        "Open kifab for this project: check, bundle, order",
        "open_kifab.py",
        (),
    ),
    (
        "add-part",
        "Add part (kifab)",
        "Search the fab's parts and add one to the project libraries",
        "add_part.py",
        ("--tab", "parts"),
    ),
)

#: Shared by both actions; runs inside KiCad's plugin environment, so it only
#: uses the standard library and (if available) kicad-python.
LAUNCHER = '''\
"""kifab KiCad plugin launcher (generated by `kifab kicad-plugin install`).

Starts kifab-gui for the project open in KiCad. No other logic lives here.
"""

import json
import os
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def project_dir():
    """The directory of the project open in KiCad, or None."""
    try:
        from kipy import KiCad
        from kipy.proto.common.types import DocumentType
    except ImportError:
        return None
    try:
        kicad = KiCad()
        for kind in (DocumentType.DOCTYPE_PCB, DocumentType.DOCTYPE_SCHEMATIC):
            for doc in kicad.get_open_documents(kind):
                path = getattr(getattr(doc, "project", None), "path", "")
                if path:
                    return Path(path)
    except Exception:
        return None
    return None


def main(extra):
    config = json.loads((HERE / "kifab-plugin.json").read_text())
    project = os.environ.get("KIFAB_PROJECT") or project_dir()
    args = [config["kifab_gui"]]
    if project:
        args.append(str(project))
    args += extra
    kwargs = {"start_new_session": True} if os.name == "posix" else {}
    subprocess.Popen(args, stdin=subprocess.DEVNULL, **kwargs)
    return 0
'''

ACTION_SCRIPT = '''\
"""kifab KiCad plugin action (generated by `kifab kicad-plugin install`)."""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from kifab_launch import main

sys.exit(main({extra!r}))
'''


class PluginError(Exception):
    pass


def default_plugin_dir() -> Path:
    """KiCad's per-user IPC plugin directory for KiCad 10."""
    home = Path.home()
    if sys.platform == "win32":
        return home / "Documents" / "KiCad" / KICAD_SERIES / "plugins"
    if sys.platform == "darwin":
        return home / "Documents" / "KiCad" / KICAD_SERIES / "plugins"
    return home / ".local" / "share" / "KiCad" / KICAD_SERIES / "plugins"


def find_kifab_gui() -> Path:
    """The ``kifab-gui`` launcher installed next to this Python."""
    names = (
        ("kifab-gui.exe", "kifab-gui") if sys.platform == "win32" else ("kifab-gui",)
    )
    scripts = Path(sys.executable).parent
    for name in names:
        if (scripts / name).is_file():
            return scripts / name
    found = shutil.which("kifab-gui")
    if found:
        return Path(found)
    raise PluginError("kifab-gui not found; install kifab with the gui extra")


def manifest() -> dict[str, object]:
    actions = []
    for ident, name, descr, script, _ in ACTIONS:
        actions.append(
            {
                "identifier": ident,
                "name": name,
                "description": descr,
                "show-button": True,
                "scopes": ["pcb", "schematic", "project_manager"],
                "entrypoint": script,
                "icons-light": ["icon-light.png"],
                "icons-dark": ["icon-dark.png"],
            }
        )
    return {
        "$schema": "https://go.kicad.org/api/schemas/v1",
        "identifier": PLUGIN_ID,
        "name": "kifab",
        "description": f"Opens kifab (version {__version__}) for the project in KiCad",
        "runtime": {"type": "python", "min_version": "3.9"},
        "actions": actions,
    }


def _png(size: int, fg: tuple[int, int, int], bg: tuple[int, int, int]) -> bytes:
    """A tiny icon: a ``k`` on a rounded square (deterministic PNG)."""
    glyph = [  # 7x9 bitmap of "k"
        "1000000",
        "1000000",
        "1000110",
        "1001100",
        "1011000",
        "1110000",
        "1011000",
        "1001100",
        "1000110",
    ]
    scale = max(1, size // 12)
    ox = (size - 7 * scale) // 2
    oy = (size - 9 * scale) // 2
    rows = []
    for y in range(size):
        row = bytearray([0])  # filter: none
        for x in range(size):
            corner = min(x, size - 1 - x) + min(y, size - 1 - y) < 3
            gx, gy = (x - ox) // scale, (y - oy) // scale
            ink = 0 <= gx < 7 and 0 <= gy < 9 and glyph[gy][gx] == "1"
            if corner:
                row += bytes((0, 0, 0, 0))
            elif ink:
                row += bytes((*fg, 255))
            else:
                row += bytes((*bg, 255))
        rows.append(bytes(row))

    def chunk(kind: bytes, data: bytes) -> bytes:
        body = kind + data
        return struct.pack(">I", len(data)) + body + struct.pack(">I", zlib.crc32(body))

    header = struct.pack(">IIBBBBB", size, size, 8, 6, 0, 0, 0)
    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", header)
        + chunk(b"IDAT", zlib.compress(b"".join(rows), 9))
        + chunk(b"IEND", b"")
    )


@dataclass(frozen=True)
class PluginInstall:
    directory: Path
    files: tuple[Path, ...]
    kifab_gui: Path


def install_plugin(
    dest: Path | None = None, *, kifab_gui: Path | None = None, force: bool = False
) -> PluginInstall:
    """Write the plugin into ``dest`` (default: KiCad's user plugin directory)."""
    target = (dest or default_plugin_dir()) / PLUGIN_DIR_NAME
    if target.exists() and not force:
        if not (target / CONFIG_NAME).is_file():
            raise PluginError(f"{target} exists and is not a kifab plugin")
        raise PluginError(f"{target} exists; use --force to replace it")
    gui = kifab_gui or find_kifab_gui()
    if target.exists():
        shutil.rmtree(target)
    target.mkdir(parents=True)
    files: dict[str, bytes] = {
        "plugin.json": (json.dumps(manifest(), indent=2) + "\n").encode(),
        "requirements.txt": b"kicad-python>=0.4\n",
        CONFIG_NAME: (
            json.dumps({"kifab_gui": str(gui), "kifab": __version__}, indent=2) + "\n"
        ).encode(),
        "kifab_launch.py": LAUNCHER.encode(),
        "icon-light.png": _png(24, (255, 255, 255), (40, 110, 180)),
        "icon-dark.png": _png(24, (20, 20, 20), (120, 180, 240)),
    }
    for _, _, _, script, extra in ACTIONS:
        files[script] = ACTION_SCRIPT.format(extra=list(extra)).encode()
    written = []
    for name, data in files.items():
        path = target / name
        path.write_bytes(data)
        written.append(path)
    return PluginInstall(target, tuple(written), gui)


def uninstall_plugin(dest: Path | None = None) -> Path | None:
    target = (dest or default_plugin_dir()) / PLUGIN_DIR_NAME
    if not target.exists():
        return None
    if not (target / CONFIG_NAME).is_file():
        raise PluginError(f"{target} is not a kifab plugin; not removing it")
    shutil.rmtree(target)
    return target
