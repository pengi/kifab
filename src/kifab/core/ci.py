"""``kifab ci init``: a GitHub Actions workflow that releases the bundle on a tag."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

from kifab import __version__
from kifab.core.git import Git
from kifab.core.project import Project

WORKFLOW = Path(".github") / "workflows" / "release.yml"
DEFAULT_IMAGE = "kicad/kicad:10.0"


class CiError(Exception):
    pass


@dataclass(frozen=True)
class CiResult:
    path: Path
    project_path: str  # the project directory relative to the repository root


def render_workflow(project_path: str, kifab_spec: str, image: str) -> str:
    """The workflow; ``project_path`` is relative to the repository root."""
    target = project_path or "."
    return f"""\
# Generated by kifab {__version__} (`kifab ci init`); edit freely, or re-run it.
# On a tag v*, kifab builds the manufacturing files with KiCad (same code path
# as a local `kifab bundle`) and attaches them to a GitHub release:
# gerbers zip, BOM, placement (CPL) and the validation report.
name: release

on:
  push:
    tags: ["v*"]

permissions:
  contents: write

jobs:
  bundle:
    runs-on: ubuntu-latest
    container:
      image: {image}
      options: --user root
    steps:
      - uses: actions/checkout@v4
        with:
          fetch-depth: 0  # git describe needs the tags

      - uses: astral-sh/setup-uv@v5

      - name: Install kifab
        run: |
          # the image's python3 (no pip/venv module needed with uv)
          uv venv /opt/kifab --python /usr/bin/python3
          uv pip install --python /opt/kifab/bin/python "{kifab_spec}"

      - name: Bundle
        run: |
          git config --global --add safe.directory "$GITHUB_WORKSPACE"
          /opt/kifab/bin/kifab bundle "{target}" --artifacts-dir release

      - name: Keep the build output
        if: always()
        uses: actions/upload-artifact@v4
        with:
          name: bundle
          path: |
            {target}/build/
            release/
          if-no-files-found: ignore

      - name: Release
        uses: softprops/action-gh-release@v2
        with:
          files: release/*
          fail_on_unmatched_files: true
"""


def init_ci(
    project: Project,
    git: Git | None,
    *,
    kifab_spec: str | None = None,
    image: str = DEFAULT_IMAGE,
    force: bool = False,
) -> CiResult:
    """Write ``.github/workflows/release.yml`` at the repository root.

    Outside a git repository the project directory is taken as the root.
    """
    root = (git.toplevel(project.directory) if git else None) or project.directory
    try:
        rel = project.directory.relative_to(root).as_posix()
    except ValueError:
        rel = ""
    path = root / WORKFLOW
    if path.exists() and not force:
        raise CiError(f"{path} exists; use --force to replace it")
    path.parent.mkdir(parents=True, exist_ok=True)
    spec = kifab_spec or f"kifab=={__version__}"
    path.write_text(render_workflow("" if rel == "." else rel, spec, image), "utf-8")
    return CiResult(path, rel)
