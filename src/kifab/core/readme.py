"""``kifab readme``: a README.md with the board's renders, schematics and BOM.

Run by hand before committing, so GitHub shows a preview of the project. The
generated part of the README lives between two marker comments; text around it
is kept. Images are written to ``images/``. Everything is rendered in a staging
directory first, so a failed run leaves the old README and images untouched.
Output is deterministic (no dates; the timestamp kicad-cli puts in SVGs is
replaced).
"""

from __future__ import annotations

import re
import shutil
import tempfile
from dataclasses import dataclass, field
from pathlib import Path

from kifab.core.bundle import bom_columns
from kifab.core.issues import Code, Issue, error, has_errors, info
from kifab.core.manufacturing import Bom, BomLine, ParseError, parse_kicad_bom
from kifab.core.pngdiff import ImageError, compare
from kifab.core.project import Project
from kifab.core.reporter import NullReporter, Reporter
from kifab.core.sourcing import sourcing_for
from kifab.fabs.base import get_fab
from kifab.kicad import sexpr
from kifab.kicad.cli import KicadCli, ToolFailed, ToolMissing
from kifab.kicad.project import locked_files
from kifab.kicad.schematic import read_schematic

README_NAME = "README.md"
IMAGE_DIR = "images"
BEGIN = "<!-- kifab:begin (generated by `kifab readme`; edits in here are lost) -->"
END = "<!-- kifab:end -->"
_BLOCK = re.compile(r"<!-- kifab:begin[^\n]*-->.*?<!-- kifab:end -->", re.DOTALL)
_TITLE = re.compile(r"<title>.*?</title>", re.DOTALL)
#: Images this command owns (stale ones are removed on the next run).
_OWNED = re.compile(r"^(schematic-.*\.svg|pcb-.*\.png)$")


@dataclass(frozen=True)
class View:
    """A 3D render of the board."""

    name: str
    side: str  # kicad-cli --side
    rotate: str | None = None  # kicad-cli --rotate
    title: str = ""


VIEWS = {
    v.name: v
    for v in (
        View("top", "top", title="Top"),
        View("bottom", "bottom", title="Bottom"),
        View("iso", "top", "-45,0,45", title="Isometric"),
    )
}
DEFAULT_VIEWS = ("top", "bottom")


@dataclass(frozen=True)
class ReadmeOptions:
    views: tuple[str, ...] = DEFAULT_VIEWS  # names from VIEWS
    width: int = 1200  # px, of each render
    bom: bool = True
    quality: str = "high"  # kicad-cli: basic (flat, fast) or high (shadows)
    force: bool = False  # run even if KiCad seems to have the project open


@dataclass
class ReadmeResult:
    path: Path
    issues: list[Issue] = field(default_factory=list)
    images: list[Path] = field(default_factory=list)
    bom: Bom | None = None
    created: bool = False  # README.md did not exist
    appended: bool = False  # README.md had no generated block; it was added

    @property
    def ok(self) -> bool:
        return not has_errors(self.issues)


@dataclass(frozen=True)
class Sheet:
    label: str
    image: str  # path relative to the README


def normalize_svg(text: str, name: str) -> str:
    """The SVG without the plot date in its ``<title>``."""
    return _TITLE.sub(f"<title>{name}</title>", text, count=1)


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _part_cell(line: BomLine) -> str:
    parts = []
    for kind, number in line.part.skus:
        if kind == "lcsc":
            parts.append(
                f"[{number}](https://www.lcsc.com/product-detail/{number}.html)"
            )
        else:
            parts.append(f"{kind.upper()} {number}")
    if line.part.mpn:
        parts.append(line.part.mpn)
    return _cell(", ".join(parts))


def bom_table(bom: Bom) -> str:
    rows = [
        "| Qty | Value | References | Footprint | Part |",
        "| ---: | --- | --- | --- | --- |",
    ]
    for line in bom.lines:
        footprint = line.footprint.rsplit(":", 1)[-1]
        rows.append(
            f"| {len(line.references)} | {_cell(line.value)} "
            f"| {_cell(', '.join(line.references))} | {_cell(footprint)} "
            f"| {_part_cell(line)} |"
        )
    return "\n".join(rows)


def render_block(
    views: list[tuple[View, str]], sheets: list[Sheet], bom: Bom | None
) -> str:
    """The generated README section, markers included."""
    out = [BEGIN, ""]
    if views:
        out += ["## PCB", ""]
        width = max(100 // len(views) - 1, 20)
        images = " ".join(
            f'<img src="{path}" alt="{v.title}" title="{v.title}" width="{width}%">'
            for v, path in views
        )
        out += [f'<p align="center">{images}</p>', ""]
    if sheets:
        out += ["## Schematic", ""]
        for sheet in sheets:
            if len(sheets) > 1:
                out += [f"### {sheet.label}", ""]
            out += [f"[![{sheet.label}]({sheet.image})]({sheet.image})", ""]
    if bom is not None:
        out += ["## Bill of materials", "", bom_table(bom), ""]
    out.append(END)
    return "\n".join(out)


def merge_readme(existing: str | None, block: str, title: str) -> tuple[str, bool]:
    """The new README text and whether ``block`` was appended (not replaced)."""
    if existing is None:
        return f"# {title}\n\n{block}\n", False
    if _BLOCK.search(existing):
        return _BLOCK.sub(lambda _: block, existing, count=1), False
    return existing.rstrip("\n") + f"\n\n{block}\n", True


class _Run:
    def __init__(
        self,
        project: Project,
        options: ReadmeOptions,
        cli: KicadCli,
        reporter: Reporter,
    ) -> None:
        self.project = project
        self.options = options
        self.cli = cli
        self.reporter = reporter
        self.result = ReadmeResult(project.directory / README_NAME)

    def add(self, issue: Issue) -> None:
        self.result.issues.append(issue)
        self.reporter.issue(issue)

    def run(self) -> ReadmeResult:
        open_files = locked_files(self.project.directory)
        if open_files and not self.options.force:
            self.add(
                error(
                    Code.KICAD_OPEN,
                    "KiCad has " + ", ".join(open_files) + " open; the saved files "
                    "may not be what you see",
                    hint="save and close KiCad, or use --force",
                )
            )
            return self.result
        unknown = [v for v in self.options.views if v not in VIEWS]
        if unknown:
            self.add(
                error(
                    Code.BAD_INPUT,
                    f"unknown view {', '.join(unknown)}",
                    hint="views: " + ", ".join(VIEWS),
                )
            )
            return self.result
        try:
            with tempfile.TemporaryDirectory(prefix="kifab-readme-") as tmp_name:
                self.build(Path(tmp_name))
        except (ToolMissing, ToolFailed) as exc:
            code = (
                Code.TOOL_MISSING if isinstance(exc, ToolMissing) else Code.TOOL_FAILED
            )
            self.add(error(code, f"readme: {exc}"))
        except (OSError, sexpr.SexprError, ParseError) as exc:
            self.add(error(Code.PARSE_ERROR, f"readme: {exc}"))
        return self.result

    def build(self, tmp: Path) -> None:
        kicad = self.project.kicad
        stage = tmp / IMAGE_DIR
        stage.mkdir()
        schematic = read_schematic(kicad.sch, kicad.name)

        sheet_dir = tmp / "svg"
        sheet_dir.mkdir()
        svgs = self.cli.export_sch_svg(kicad.sch, sheet_dir)
        # The root sheet first, the others by name.
        svgs.sort(key=lambda p: (p.stem != kicad.name, p.stem))
        sheets = []
        for svg in svgs:
            image = f"schematic-{svg.stem}.svg"
            text = svg.read_text(encoding="utf-8")
            (stage / image).write_text(normalize_svg(text, svg.stem), encoding="utf-8")
            prefix = f"{kicad.name}-"
            label = svg.stem[len(prefix) :] if svg.stem.startswith(prefix) else "Main"
            sheets.append(Sheet(label, f"{IMAGE_DIR}/{image}"))
        self.reporter.step("schematic", f"{len(sheets)} sheet(s)")

        views = []
        for name in self.options.views:
            view = VIEWS[name]
            image = f"pcb-{name}.png"
            self.cli.render_pcb(
                kicad.pcb,
                stage / image,
                side=view.side,
                width=self.options.width,
                height=self.options.width * 3 // 4,
                rotate=view.rotate,
                quality=self.options.quality,
            )
            views.append((view, f"{IMAGE_DIR}/{image}"))
            state = self.keep_if_unchanged(stage / image)
            self.reporter.step("render", f"{view.title} ({state})")

        bom = None
        if self.options.bom:
            sourcing = self.project.sourcing() or sourcing_for(get_fab("jlcpcb"))
            columns, specs = bom_columns(schematic, sourcing)
            raw = tmp / "bom.csv"
            self.cli.export_bom(kicad.sch, raw, columns)
            bom = parse_kicad_bom(raw.read_text(encoding="utf-8"), specs)
            self.reporter.step("BOM", f"{len(bom.lines)} lines, {bom.part_count} parts")

        block = render_block(views, sheets, bom)
        path = self.result.path
        existing = path.read_text(encoding="utf-8") if path.is_file() else None
        text, appended = merge_readme(existing, block, self.project.name)
        self.publish(stage, text)
        self.result.bom = bom
        self.result.created = existing is None
        self.result.appended = appended
        if appended:
            self.add(
                info(
                    Code.README_APPENDED,
                    f"{README_NAME} had no generated section; added it at the end",
                    hint="move it where you want; later runs update it in place",
                )
            )
        self.reporter.step("README", path.name)

    def keep_if_unchanged(self, new: Path) -> str:
        """Put the old render back over ``new`` if the two differ only by noise.

        Ray traced renders differ in every run; rewriting the PNG for that
        would fill the git history with binary changes."""
        old = self.project.directory / IMAGE_DIR / new.name
        if not old.is_file():
            return "new"
        old_bytes = old.read_bytes()
        try:
            difference = compare(old_bytes, new.read_bytes())
        except ImageError:
            return "updated"
        if difference.real():
            return "updated"
        new.write_bytes(old_bytes)
        return "unchanged"

    def publish(self, stage: Path, text: str) -> None:
        target = self.project.directory / IMAGE_DIR
        target.mkdir(exist_ok=True)
        new = {p.name for p in stage.iterdir()}
        for old in target.iterdir():
            if old.name not in new and _OWNED.match(old.name):
                old.unlink()
        for image in sorted(stage.iterdir()):
            shutil.copyfile(image, target / image.name)
            self.result.images.append(target / image.name)
        self.result.path.write_text(text, encoding="utf-8", newline="\n")


def generate_readme(
    project: Project,
    options: ReadmeOptions | None = None,
    *,
    cli: KicadCli | None = None,
    reporter: Reporter | None = None,
) -> ReadmeResult:
    """(Re)create the README of ``project``; never raises for bad input."""
    run = _Run(
        project,
        options or ReadmeOptions(),
        cli or KicadCli(),
        reporter or NullReporter(),
    )
    return run.run()
