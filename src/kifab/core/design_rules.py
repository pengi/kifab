"""Write a fab's design-rule profile into a project and detect drift.

``.kicad_dru``: kifab owns a managed block right after ``(version 1)``; custom
rules the user adds after the block are kept (later rules win in KiCad, so a
user rule there is a deliberate override). ``.kicad_pro``: the board-setup
constraints are set to the profile's minimums.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

from kifab.core import managed
from kifab.core.config import CONFIG_NAME, ConfigError
from kifab.core.issues import Code, Issue, error, info
from kifab.core.project import Project
from kifab.fabs.rules import DesignRuleProfile
from kifab.kicad.project import ProjectFile

DRU_MARKERS = managed.Markers(
    "# >>> kifab design rules (managed block: `kifab rules apply` rewrites it)",
    "# <<< kifab design rules",
)
DRU_VERSION = "(version 1)"
TOLERANCE = 1e-6


def render_block(profile: DesignRuleProfile) -> str:
    """The managed block's content (without marker lines)."""
    lines = [
        f"# Generated by kifab from the {profile.describe()}.",
        "# Do not edit inside this block; change kifab.toml and run `kifab rules apply`.",
    ]
    if profile.source:
        lines.append(f"# Source: {profile.source}")
    out = "\n".join(lines) + "\n"
    for rule in profile.rules:
        out += "\n" + rule.render() + "\n"
    return out


def render_dru(profile: DesignRuleProfile, existing: str | None) -> str:
    """A complete ``.kicad_dru``: version, managed block, then the user's rules."""
    user = ""
    if existing:
        parts = managed.split(existing, DRU_MARKERS)
        if parts.block is not None:
            user = parts.after
        else:
            # first apply on an existing project: keep its rules after the block
            user = existing
        user_lines = user.splitlines(keepends=True)
        while user_lines and (
            not user_lines[0].strip() or user_lines[0].strip().startswith("(version")
        ):
            user_lines.pop(0)
        user = "".join(user_lines)
    text = DRU_VERSION + "\n" + managed.render(DRU_MARKERS, render_block(profile))
    if user:
        text += "\n" + user if not user.startswith("\n") else user
    return text


@dataclass(frozen=True)
class ApplyResult:
    changed: tuple[Path, ...]
    backup: Path | None


def apply_rules(project: Project, *, force: bool = False) -> ApplyResult:
    """Write the profile into ``.kicad_dru`` and ``.kicad_pro`` (KiCad must be closed).

    Board-setup values below the fab's minimum are raised to it; values that are
    already stricter are kept.
    """
    profile = project.design_rules()
    if profile is None:
        raise ConfigError(
            f"no {CONFIG_NAME} in {project.directory}: kifab does not know the fab"
        )
    project.ensure_closed(force)
    dru, pro = project.kicad.dru, project.kicad.pro

    old_dru = dru.read_text(encoding="utf-8") if dru.is_file() else None
    new_dru = render_dru(profile, old_dru)
    pro_file = ProjectFile.load(pro)
    old_pro = pro_file.dumps()
    current = pro_file.board_rules()
    # raise what is below the fab's minimum; stricter values are the designer's
    pro_file.set_board_rules(
        {
            key: max(wanted, current.get(key, wanted))
            for key, wanted in profile.constraints.values().items()
        }
    )
    new_pro = pro_file.dumps()

    changes = [
        (p, t) for p, old, t in ((dru, old_dru, new_dru), (pro, old_pro, new_pro))
    ]
    changed = [
        (p, t) for p, t in changes if not p.is_file() or p.read_text("utf-8") != t
    ]
    backup = project.backup([p for p, _ in changed]) if changed else None
    for path, text in changed:
        path.write_text(text, encoding="utf-8")
    return ApplyResult(tuple(p for p, _ in changed), backup)


def check_rules(project: Project) -> list[Issue]:
    """Drift between the project's rules and the fab profile in ``kifab.toml``."""
    profile = project.design_rules()
    if profile is None:
        return []
    hint = "run `kifab rules apply`"
    issues: list[Issue] = []
    dru = project.kicad.dru
    dru_rel = project.rel(dru)
    if not dru.is_file():
        issues.append(
            error(Code.RULES_MISSING, "no .kicad_dru", path=dru_rel, hint=hint)
        )
    else:
        block = managed.split(dru.read_text(encoding="utf-8"), DRU_MARKERS).block
        if block is None:
            issues.append(
                error(
                    Code.RULES_MISSING,
                    "the .kicad_dru has no kifab design-rules block",
                    path=dru_rel,
                    hint=hint,
                )
            )
        elif block != render_block(profile):
            issues.append(
                error(
                    Code.RULES_DRIFT,
                    f"the kifab design rules were edited or are out of date "
                    f"({profile.describe()})",
                    path=dru_rel,
                    hint=hint,
                )
            )
    pro_rel = project.rel(project.kicad.pro)
    actual = ProjectFile.load(project.kicad.pro).board_rules()
    for key, wanted in profile.constraints.values().items():
        have = actual.get(key)
        if have is None:
            issues.append(
                error(
                    Code.RULES_MISSING,
                    f"board setup constraint {key} is not set (fab: {wanted:g} mm)",
                    path=pro_rel,
                    hint=hint,
                )
            )
        elif have < wanted - TOLERANCE:
            issues.append(
                error(
                    Code.RULES_LOOSENED,
                    f"board setup constraint {key} is {have:g} mm, below the fab's "
                    f"{wanted:g} mm",
                    path=pro_rel,
                    hint=hint,
                )
            )
        elif have > wanted + TOLERANCE:
            issues.append(
                info(
                    Code.RULES_DRIFT,
                    f"board setup constraint {key} is {have:g} mm, stricter than "
                    f"the fab's {wanted:g} mm",
                    path=pro_rel,
                )
            )
    return issues
